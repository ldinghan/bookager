const fs = require('fs');
const path = require('path');

const ICONS_DIR = path.join(__dirname, '..', 'public', 'icons');
const OUTPUT_FILE = path.join(__dirname, '..', 'app', 'iconsManifest.ts');
const ALLOWED_EXT = new Set(['.png', '.jpg', '.jpeg', '.svg', '.webp', '.gif', '.ico']);

const files = fs
    .readdirSync(ICONS_DIR)
    .filter((name) => ALLOWED_EXT.has(path.extname(name).toLowerCase()))
    .sort();

const body = `// AUTO-GENERATED by scripts/generate-icons-manifest.js — do not edit by hand.
// Re-runs on \`npm run dev\` and \`npm run build\`.

const ICONS: readonly string[] = ${JSON.stringify(files, null, 4)} as const;

export default ICONS;
`;

fs.writeFileSync(OUTPUT_FILE, body);
console.log(`Wrote ${files.length} icon(s) to ${path.relative(process.cwd(), OUTPUT_FILE)}`);
